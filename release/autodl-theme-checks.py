"""autodl theme stylesheet checks run inside a started, healthy ruTorrent container.

The release gate pipes this file to `docker exec -i <container> python3 -`.

  served     every theme in THEMES has its ruTorrent theme directory, and
             nginx serves its generated autodl stylesheet (with the login)
             with the Filters layout; a theme autodl ships itself is unchanged

The container's USERNAME and PASSWORD environment set the basic-auth login.
The last line printed is a JSON summary.
"""
import base64
import json
import os
import pathlib
import sys
import urllib.error
import urllib.request

BASE = "http://127.0.0.1"
LOGIN = base64.b64encode((os.environ["USERNAME"] + ":" + os.environ["PASSWORD"]).encode()).decode()
MARKER = b"/* Generated by Appbox patch-autodl-rutorrent-html5.py; rewritten on every start. */"
LIST_RULE = b"#autodl-filters-list{height:auto !important;max-height:min(420px, calc(100vh - 220px)) !important;overflow-y:auto !important}"
THEMES_DIR = pathlib.Path("/var/www/rutorrent/plugins/theme/themes")
# Theme directory -> autodl stylesheet whose rules the generated file starts with (None: layout only).
THEMES = {
    "club-QuickBox": None,
    "DarkBetter": "dark",
    "MaterialDesign": "dark",
    "OblivionBlue": "oblivion",
}


def get(path, auth=True):
    request = urllib.request.Request(BASE + path)
    if auth:
        request.add_header("Authorization", "Basic " + LOGIN)
    try:
        with urllib.request.urlopen(request, timeout=60) as response:
            return response.status, response.read()
    except urllib.error.HTTPError as error:
        return error.code, error.read()


def served():
    result = {}
    for theme, colours in THEMES.items():
        assert (THEMES_DIR / theme / "style.css").is_file(), f"theme {theme} is missing"
        path = f"/plugins/autodl-rutorrent/css/{theme.lower()}.min.css"
        status, body = get(path)
        assert status == 200, f"{path} returned HTTP {status}"
        assert body.startswith(MARKER + b"\n"), f"{path} is not the generated stylesheet"
        assert LIST_RULE in body, f"{path} lacks the filter list rule"
        assert b"sourceMappingURL" not in body, f"{path} keeps a source map reference"
        if colours:
            status, source = get(f"/plugins/autodl-rutorrent/css/{colours}.min.css")
            assert status == 200, f"{colours}.min.css returned HTTP {status}"
            assert b".autodl-listbox{" in body and b"#autodl-irssi-log" in body, f"{path} lacks the {colours} rules"
            assert not source.startswith(MARKER), f"{colours}.min.css was overwritten"
        unauth, _ = get(path, auth=False)
        assert unauth == 401, f"{path} without a login returned HTTP {unauth}"
        result[theme] = len(body)
    return result


def main():
    mode = sys.argv[1] if len(sys.argv) == 2 else ""
    assert mode == "served", "usage: served"
    print(json.dumps({"served": served()}, sort_keys=True))


if __name__ == "__main__":
    main()
